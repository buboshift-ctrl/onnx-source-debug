#!/usr/bin/env python3
"""
조인 단계 (join) — 정보 트랙과 코드 트랙이 만나는 유일한 지점.

역할: 코드 트랙이 낸 C 소스의 "노드 마커" 주석(`/* onnx_node_name: <name> */`)을 찾아,
그 직후에 `#line <L> "<원본.py>"` 를 삽입한다. `<L>`/`<원본.py>` 는 정보 트랙이 만든
locmap 에서 `node.name` 으로 조인해 가져온다. 노드 블록이 끝나면(`/* onnx_node_end */`
또는 다음 마커) `#line` 으로 다시 C 파일에 매핑을 되돌린다.

이렇게 심은 C 를 `gcc -g` 로 컴파일하면 DWARF `.debug_line` 이 원본 `.py` 파일:줄을
그대로 가리키므로, gdb 에서 원본 PyTorch 소스 줄에 중단점을 걸 수 있다. (배경: 실제 ARX
파이프라인의 EmitC→C 경로는 MLIR→LLVM dialect 를 안 거쳐 정식 DWARF lowering 이 없고,
onnx-mlir 의 `--enable-debug-info` 경로도 깨져 있다 — debug_info_investigation.md Part A2.)

아키텍처상의 위치 (TASK_formalize_architecture_v3.md):
  - 조인 키는 오직 `node.name`.
  - 정보 트랙(info_track.py)과 코드 트랙(code_track.py) 어느 쪽에도 의존하지 않는다
    (문자열 C 소스 + dict locmap 만 받는다).

공개 API:
  inject(c_source: str, locmap: dict) -> str
  inject_with_stats(c_source: str, locmap: dict, ...) -> (str, dict)
  find_node_markers(c_source: str) -> list[str]

결정성: 순수 텍스트 변환. 타임스탬프/난수 없음. 같은 (C, locmap) → 바이트 동일 출력.
"""
from __future__ import annotations

import re
from typing import Any

# 주석 안의  onnx_node_name : <name>  /  onnx-node = "<name>"  등을 관대하게 인식
_MARKER_RE = re.compile(
    r"onnx[_-]node(?:_name)?\s*[:=]\s*\"?(?P<name>[A-Za-z0-9_.:/-]+)\"?",
    re.IGNORECASE,
)
_END_MARKER_RE = re.compile(r"onnx[_-]node(?:_name)?[_-]end", re.IGNORECASE)

# inject 가 붙이는 파일 헤더의 물리적 줄 수 (되돌림 #line 계산에 사용).
# 헤더 텍스트가 바뀌어도 줄 수(3)는 유지할 것.
_HEADER_LINES = 3
_HEADER = (
    "/* auto-generated by join.py — do not edit.\n"
    "   #line directives project ONNX-node source locations (from locmap)\n"
    "   onto this C file so `gcc -g` emits DWARF pointing at the original .py. */"
)


def _resolve(path: str, base: str | None) -> str:
    """locmap 의 file 이 상대경로면 base(=_meta.path_base) 기준 절대경로로. gcc/gdb 가 소스를 찾을 수 있게."""
    import os

    if os.path.isabs(path) or not base:
        return path
    return os.path.normpath(os.path.join(base, path))


def find_node_markers(c_source: str) -> list[str]:
    """C 소스에서 노드 마커에 적힌 node.name 들을 등장 순서대로 (중복 포함) 돌려준다."""
    names: list[str] = []
    for raw in c_source.splitlines():
        if _END_MARKER_RE.search(raw):
            continue
        m = _MARKER_RE.search(raw)
        if m:
            names.append(m.group("name"))
    return names


def inject_with_stats(
    c_source: str,
    locmap: dict[str, Any],
    *,
    out_c_name: str = "generated.line.c",
    resolve_paths: bool = False,
) -> tuple[str, dict]:
    """
    c_source 에 #line 지시자를 삽입한 새 텍스트와 통계를 돌려준다.
    통계: {"matched": [...], "unknown": [...], "directives": int, "nodes_in_locmap": int}
    resolve_paths=True 면 locmap 의 상대 file 경로를 _meta.path_base 기준 절대경로로 펴서 #line 에 쓴다.
    """
    nodes = locmap.get("nodes", {})
    path_base = locmap.get("_meta", {}).get("path_base") if resolve_paths else None
    lines = c_source.splitlines(keepends=False)
    out: list[str] = []
    matched: list[str] = []
    unknown: list[str] = []
    directives = 0
    in_node_block = False

    def emit_reset_to_c() -> None:
        nonlocal directives
        # 이 directive 다음에 올 실제 코드 줄의 물리적 줄 번호로 되돌린다.
        # out[i] 의 물리적 줄 = i + 1 + _HEADER_LINES. append 전 len(out)=cur 이면
        # directive 는 out[cur], 그 다음 줄은 out[cur+1] = 물리 cur + 2 + _HEADER_LINES.
        out.append(f'#line {len(out) + 2 + _HEADER_LINES} "{out_c_name}"')
        directives += 1

    for raw in lines:
        end_hit = bool(_END_MARKER_RE.search(raw))
        m = None if end_hit else _MARKER_RE.search(raw)

        if m:
            name = m.group("name")
            out.append(raw)  # 마커 줄은 그대로 둔다 (사람이 읽는 용도)
            entry = nodes.get(name)
            if entry and "file" in entry and "line" in entry:
                f = _resolve(entry["file"], path_base)
                out.append(f'#line {int(entry["line"])} "{f}"')
                directives += 1
                matched.append(name)
                in_node_block = True
            else:
                unknown.append(name)
                if in_node_block:
                    emit_reset_to_c()
                    in_node_block = False
            continue

        if end_hit and in_node_block:
            out.append(raw)
            emit_reset_to_c()
            in_node_block = False
            continue

        out.append(raw)

    text = _HEADER + "\n" + "\n".join(out) + "\n"
    stats = {
        "matched": matched,
        "unknown": unknown,
        "directives": directives,
        "nodes_in_locmap": len(nodes),
    }
    return text, stats


def inject(c_source: str, locmap: dict[str, Any], **opts: Any) -> str:
    """TASK v3 공개 시그니처. #line 을 심은 C 소스 문자열만 돌려준다."""
    text, _ = inject_with_stats(c_source, locmap, **opts)
    return text


# --------------------------------------------------------------------------- #
# CLI (하위호환: inject_line_directives.py 의 일반 모드가 이걸 부른다)
# --------------------------------------------------------------------------- #
def main(argv: list[str] | None = None) -> int:
    import argparse
    import json
    import os
    import sys

    ap = argparse.ArgumentParser(description="조인 단계 — 생성 C 에 #line 투영")
    ap.add_argument("c_file", help="입력 C 파일 (코드 트랙 산출물)")
    ap.add_argument("locmap", help="locmap JSON (정보 트랙 산출물)")
    ap.add_argument("-o", "--output", help="출력 C 파일 (생략 시 stdout)")
    ap.add_argument("--c-name", help="#line 되돌림에 쓸 출력 C 파일명 (기본: -o 의 basename)")
    ap.add_argument("--resolve-paths", action="store_true",
                    help="locmap 상대 file 경로를 _meta.path_base 기준 절대경로로 펴서 #line 에 기록")
    args = ap.parse_args(argv)

    with open(args.locmap, encoding="utf-8") as fh:
        locmap = json.load(fh)
    with open(args.c_file, encoding="utf-8") as fh:
        c_src = fh.read()

    out_name = args.c_name or os.path.basename(args.output or "generated.line.c")
    injected, stats = inject_with_stats(
        c_src, locmap, out_c_name=out_name, resolve_paths=args.resolve_paths
    )
    if args.output:
        with open(args.output, "w", encoding="utf-8") as fh:
            fh.write(injected)
        print(
            f"기록: {args.output}  (#line {stats['directives']}개, "
            f"매핑된 노드 {len(stats['matched'])}, 미매핑 {len(stats['unknown'])})",
            file=sys.stderr,
        )
        if stats["unknown"]:
            print("  locmap 에 없는 노드 마커: " + ", ".join(stats["unknown"]), file=sys.stderr)
    else:
        sys.stdout.write(injected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
